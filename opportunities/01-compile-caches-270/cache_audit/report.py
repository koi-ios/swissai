"""Render an AuditResult: markdown table, model-launch env snippet, JSON."""

from __future__ import annotations

import json
import os
from typing import Any

from .audit import JIT, AuditResult
from .classify import human
from .cluster import Root

GATE_TEXT = {0: "PASS", 2: "FAIL (command failed)", 10: "FAIL (known cache not redirected)",
             11: "FAIL (unknown cache root)", 12: "FAIL (variable no longer relocates its cache)"}


def _short(p: str, sb_root: str | None) -> str:
    if sb_root and p.startswith(sb_root):
        return "<sandbox>" + p[len(sb_root):]
    return p


def roots_table(roots: list[Root], sb_root: str | None = None) -> str:
    rows = ["| root | KB entry | variable | files | size | contents | abs paths baked | how written | writers |",
            "|---|---|---|---:|---:|---|---:|---|---|"]
    for r in roots:
        var = r.entry.primary_var if r.entry and r.entry.primary_var else "-"
        writers = ", ".join(f"{w} ({n})" for w, n in r.writers.most_common(2)) or "-"
        rows.append(f"| `{_short(r.path, sb_root)}` | {r.label} | `{var}` | {r.contents.files} | "
                    f"{human(r.contents.bytes)} | {r.contents.summary()} | {len(r.contents.path_baked)} | "
                    f"{r.write_pattern()} | {writers} |")
    return "\n".join(rows)


def toml_snippet(res: AuditResult, sizes: dict[str, int] | None = None) -> str:
    lines = ["# Generated by cache-audit. {jit_cache} is resolved by sml per image digest and GPU arch.",
             "# Paste into the env TOML's [env] table."]
    for var, val in res.proposal.items():
        owners = ", ".join(res.proposal_entries.get(var, []))
        note = f"  # {owners}" if owners else ""
        lines.append(f'{var} = "{val}"{note}')
    return "\n".join(lines) + "\n"


def markdown(res: AuditResult) -> str:
    out = [f"# cache-audit report", "", f"Command: `{' '.join(res.argv)}`", "",
           f"**Gate: {GATE_TEXT.get(res.exit_code, res.exit_code)}** (exit {res.exit_code})"]
    for r in res.reasons:
        out.append(f"- {r}")
    for name, run in res.runs.items():
        sb_root = run.sb_root
        out += ["", f"## Run `{name}`: exit {run.rec.returncode}, {run.rec.wall_s:.1f} s, "
                    f"tracers {'+'.join(run.rec.tracers)}"]
        if run.rec.notes:
            out.append("Notes: " + "; ".join(run.rec.notes))
        if run.env_set:
            out.append("Variables set: " + ", ".join(f"`{k}`" for k in sorted(run.env_set)))
        out += ["", roots_table(run.roots, sb_root)]
    if res.verification:
        out += ["", "## Mapping verified by re-run", "", "| KB entry | verdict |", "|---|---|"]
        out += [f"| {k} | {v} |" for k, v in res.verification.items()]
    if res.outside:
        out += ["", "## Persisted outside the cache dir in the redirected run", ""]
        out += [f"- `{r.path}` ({r.label}, {r.contents.files} files, {human(r.contents.bytes)})" for r in res.outside]
    if res.temporaries:
        out += ["", "## Leaked temporary files (randomly named, never reused; not gated)", ""]
        for r in res.temporaries[:20]:
            w = ", ".join(r.writers) or "no Python frame (C/Cython)"
            out.append(f"- `{r.path}` ({human(r.contents.bytes)}; writer: {w})")
    if res.builds:
        out += ["", "## Warm run: builds avoided", "",
                "| KB entry | binaries cold | binaries rebuilt warm | files cold | files written warm |",
                "|---|---:|---:|---:|---:|"]
        for k, v in res.builds.items():
            out.append(f"| {k} | {v['binaries_cold']} | {v['binaries_warm']} | {v['files_cold']} | {v['files_warm']} |")
        if "warm" in res.runs and "redirect" in res.runs:
            out.append("")
            out.append(f"Wall time: cold {res.runs['redirect'].rec.wall_s:.1f} s, "
                       f"warm {res.runs['warm'].rec.wall_s:.1f} s")
    if "relocate" in res.runs:
        out += ["", "## Relocation (cache copied to a new absolute path)", ""]
        out.append("Files rewritten after the move, per entry: " +
                   (", ".join(f"{k}: {v}" for k, v in res.relocation.items()) or "none (relocatable)"))
    if res.readonly:
        out += ["", "## Read-only cache", "", f"```\n{json.dumps(res.readonly, indent=2)}\n```"]
    out += ["", "## Env snippet", "", "```toml", toml_snippet(res).rstrip(), "```"]
    return "\n".join(out) + "\n"


def to_json(res: AuditResult) -> dict[str, Any]:
    def root(r: Root) -> dict[str, Any]:
        return {"path": r.path, "entry": r.label, "anchor": r.anchor,
                "variable": r.entry.primary_var if r.entry else None,
                "files": r.contents.files, "bytes": r.contents.bytes,
                "by_class": dict(r.contents.by_class), "bytes_by_class": dict(r.contents.bytes_by_class),
                "path_baked": len(r.contents.path_baked), "path_baked_examples": r.contents.path_baked[:5],
                "write_pattern": r.write_pattern(), "ops": dict(r.ops),
                "writers": dict(r.writers.most_common(10)), "failed_writes": r.failed_writes[:20]}

    return {
        "argv": res.argv, "exit_code": res.exit_code, "gate": GATE_TEXT.get(res.exit_code),
        "reasons": res.reasons, "proposal": res.proposal, "proposal_entries": res.proposal_entries,
        "verification": res.verification, "builds": res.builds, "relocation": res.relocation,
        "readonly": res.readonly,
        "outside": [root(r) for r in res.outside],
        "temporaries": [root(r) for r in res.temporaries],
        "runs": {n: {"returncode": r.rec.returncode, "wall_s": round(r.rec.wall_s, 3),
                     "tracers": r.rec.tracers, "notes": r.rec.notes, "env_set": r.env_set,
                     "roots": [root(x) for x in r.roots], "subprocesses": r.rec.subprocesses[:50],
                     "log_tail": r.log_tail}
                 for n, r in res.runs.items()},
    }


def write_all(res: AuditResult, out_dir: str) -> dict[str, str]:
    os.makedirs(out_dir, exist_ok=True)
    paths = {"md": os.path.join(out_dir, "report.md"), "json": os.path.join(out_dir, "report.json"),
             "toml": os.path.join(out_dir, "env-snippet.toml")}
    with open(paths["md"], "w") as f:
        f.write(markdown(res))
    with open(paths["json"], "w") as f:
        json.dump(to_json(res), f, indent=2, default=str)
    with open(paths["toml"], "w") as f:
        f.write(toml_snippet(res))
    return paths


__all__ = ["markdown", "to_json", "toml_snippet", "write_all", "JIT"]
