#!/usr/bin/env python3
"""One-screen view of every project, built from project.toml and budget/.

  portfolio.py            print it for a terminal        (make status)
  portfolio.py --write    rewrite PORTFOLIO.md           (make portfolio)
  portfolio.py --check    fail if PORTFOLIO.md is stale  (part of make check)
"""
from __future__ import annotations

import sys

from lib import ROOT, card_name, money, projects, read_csv, workspace

OUT = ROOT / "PORTFOLIO.md"


def rows() -> tuple[list[dict], dict]:
    plan = read_csv(ROOT / "budget/plan.csv")
    ledger = read_csv(ROOT / "budget/ledger.csv")
    ws = workspace()
    out = []
    for p in projects():
        c = p["card"] or {}
        ups = "; ".join(f"{card_name(u['repo'])} {u.get('target', '')} ({u.get('state', '?')})" for u in c.get("upstream", []))
        out.append({
            "id": c.get("id", p["slug"][:2]), "slug": p["slug"], "stage": c.get("stage", "?"), "state": c.get("state", "?"),
            "next": c.get("next_action", "no project.toml"), "who": c.get("stakeholder", ""), "upstream": ups or "none",
            "planned": money(plan, "est_usd", p["slug"]), "spent": money(ledger, "actual_usd", p["slug"]),
        })
    totals = {
        "planned": money(plan, "est_usd"), "spent": money(ledger, "actual_usd"),
        "active": sum(r["state"] == "active" for r in out), "max_active": ws["projects"]["max_active"],
        "total": ws["budget"]["total_usd"], "month": ws["budget"]["month_usd"], "cap": ws["budget"]["project_cap_usd"],
    }
    return out, totals


def usd(x: float) -> str:
    return f"${x:.0f}" if x == int(x) else f"${x:.2f}"


def markdown() -> str:
    data, t = rows()
    lines = [
        "<!-- generated by `make portfolio` from opportunities/*/project.toml and budget/; do not edit -->",
        "# Portfolio",
        "",
        f"{t['active']} of {len(data)} projects active (limit {t['max_active']}). "
        f"Modal: {usd(t['planned'])} planned, {usd(t['spent'])} spent; caps {usd(t['cap'])} a project, "
        f"{usd(t['month'])} a month, {usd(t['total'])} in all.",
        "",
        "| # | Project | Stage | State | Next action | Stakeholder | Upstream target (state) | Planned | Spent |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in data:
        state = f"**{r['state']}**" if r["state"] == "active" else r["state"]
        lines.append(f"| {r['id']} | [{r['slug'][3:]}](opportunities/{r['slug']}/STATUS.md) | {r['stage']} | {state} | "
                     f"{r['next']} | {r['who']} | {r['upstream']} | {usd(r['planned'])} | {usd(r['spent'])} |")
    lines += ["", "Stages and gates: `pipeline/DOCTRINE.md`, D1. To change a row, edit that project's `project.toml` "
              "and run `make portfolio`."]
    return "\n".join(lines) + "\n"


def terminal() -> str:
    data, t = rows()
    out = [f"{t['active']}/{len(data)} active (limit {t['max_active']})   Modal planned {usd(t['planned'])}, "
           f"spent {usd(t['spent'])} of {usd(t['total'])}"]
    for r in data:
        mark = "*" if r["state"] == "active" else " "
        out.append(f"{mark}{r['id']} {r['slug'][3:]:<22.22} {r['stage']:<8.8} {r['state']:<7.7} "
                   f"{usd(r['planned']):>4}/{usd(r['spent']):<4} {r['next'][:70]}")
        out.append(f"     {r['upstream'][:60]:<60}  {r['who'][:45]}")
    return "\n".join(out)


def main() -> int:
    if "--write" in sys.argv:
        OUT.write_text(markdown(), encoding="utf-8")
        print(f"portfolio: wrote {OUT.name}")
    elif "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != markdown():
            print("portfolio: PORTFOLIO.md is stale; run `make portfolio`")
            return 1
        print("portfolio: ok")
    else:
        print(terminal())
    return 0


if __name__ == "__main__":
    sys.exit(main())
